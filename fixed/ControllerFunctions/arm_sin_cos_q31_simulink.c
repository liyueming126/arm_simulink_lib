/* Clip 64-bit signed to Q31 range */
static q31_t clip_q63_to_q31(q63_t x)
{
    /* Check if the upper 33 bits are all the same (proper sign extension) */
    int32_t upper = (int32_t)(x >> 32);
    int32_t sign = (int32_t)((int64_t)x >> 31);
    if (upper != sign) {
        /* Overflow: clip to min/max Q31 */
        return (int32_t)0x7FFFFFFF ^ ((int32_t)(x >> 63));
    }
    return (q31_t)x;
}

/* CMSIS-compatible Q31 sin_cos using cubic Hermite interpolation */
void arm_sin_cos_q31(q31_t theta, q31_t *pSinVal, q31_t *pCosVal)
{
    uint32_t idxS, idxC;
    q31_t fract;
    q31_t f1, f2, d1, d2;
    q31_t Dn, Df;
    q63_t temp;

    /* Map theta to table index (0..511) */
    idxS = (uint32_t)theta >> CONTROLLER_Q31_SHIFT;
    /* For cos = sin(theta + pi/2): add 128 = 512/4 table entries */
    idxC = (idxS + (TABLE_SIZE >> 2u)) & (TABLE_SIZE - 1u);

    /* Fractional part (0..255), scaled up by 8 for interpolation */
    fract = (theta - ((q31_t)idxS << CONTROLLER_Q31_SHIFT)) << 8u;

    /* ---- cos(theta) = sin(theta + pi/2) ---- */
    f1 = sinTable_q31[idxC];
    f2 = sinTable_q31[idxC + 1u];
    /* Derivative of cos = -sin */
    d1 = -sinTable_q31[idxS];
    d2 = -sinTable_q31[idxS + 1u];

    /* Cubic Hermite interpolation (CMSIS method) */
    Dn = (q31_t)(0x1921FB5u);        /* 2*pi/TABLE_SIZE in Q31 */
    Df = f2 - f1;

    temp = (q63_t)Dn * ((q63_t)d1 + d2);
    temp = temp - ((q63_t)Df << 32);
    temp = (q63_t)fract * (temp >> 31);
    temp = temp + (((q63_t)3 * Df << 31) - (d2 + ((q63_t)d1 << 1)) * Dn);
    temp = (q63_t)fract * (temp >> 31);
    temp = temp + (q63_t)d1 * Dn;
    temp = (q63_t)fract * (temp >> 31);

    *pCosVal = clip_q63_to_q31((temp >> 31) + (q63_t)f1);

    /* ---- sin(theta) ---- */
    f1 = sinTable_q31[idxS];
    f2 = sinTable_q31[idxS + 1u];
    /* Derivative of sin = cos = sin(theta + pi/2) */
    d1 = sinTable_q31[idxC];
    d2 = sinTable_q31[idxC + 1u];

    Df = f2 - f1;

    temp = (q63_t)Dn * ((q63_t)d1 + d2);
    temp = temp - ((q63_t)Df << 32);
    temp = (q63_t)fract * (temp >> 31);
    temp = temp + (((q63_t)3 * Df << 31) - (d2 + ((q63_t)d1 << 1)) * Dn);
    temp = (q63_t)fract * (temp >> 31);
    temp = temp + (q63_t)d1 * Dn;
    temp = (q63_t)fract * (temp >> 31);

    *pSinVal = clip_q63_to_q31((temp >> 31) + (q63_t)f1);
}

